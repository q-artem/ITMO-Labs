-- Сделать запрос для получения атрибутов из указанных таблиц, применив фильтры по указанным условиям:
-- Таблицы: Н_ЛЮДИ, Н_СЕССИЯ.
-- Вывести атрибуты: Н_ЛЮДИ.ИМЯ, Н_СЕССИЯ.ИД.
-- Фильтры (AND):
-- a) Н_ЛЮДИ.ОТЧЕСТВО < Владимирович.
-- b) Н_СЕССИЯ.ДАТА > 2002-01-04.
-- Вид соединения: RIGHT JOIN.

EXPLAIN ANALYZE
SELECT
    "Н_ЛЮДИ"."ИМЯ",
    "Н_СЕССИЯ"."ИД"
FROM
    "Н_ЛЮДИ"
        RIGHT JOIN
    "Н_СЕССИЯ"
    ON "Н_ЛЮДИ"."ИД" = "Н_СЕССИЯ"."ЧЛВК_ИД"  -- Предполагаемое условие связи (замените на реальное)
WHERE
    "Н_ЛЮДИ"."ОТЧЕСТВО" < 'Владимирович'
  AND "Н_СЕССИЯ"."ДАТА" > '2002-01-04';